const fence=(lang,t)=>'```'+lang+'\n'+t+'\n```';
function render(p){
  const sys=p.messages.filter(m=>m.role==='system').map(m=>m.content).join('\n\n');
  const user=p.messages.filter(m=>m.role!=='system').map(m=>m.content).join('\n\n');
  return ['# '+p.title,'',
    'Generated by `node scripts/export-handover.js` from the code. Do not edit by hand: change the code, then run the script.','',
    'Where it lives: '+p.where+'.','',
    'Structured output name: `'+p.schemaName+'`.','',
    '## System prompt','',fence('text',sys),'',
    '## User message (sample, fictional, already masked)','',fence('text',user),'',
    '## Output schema','',fence('json',JSON.stringify(p.schema,null,2)),
    ...(p.after?['','## What happens to the answer','',p.after]:[]),''].join('\n');
}

// ---------- Cost estimate (handover/cost-estimate.md) ----------
// Token counts are estimated at 4 characters a token: no API key was available to run count_tokens.
// Prices are Anthropic's published list prices per million tokens, as of the date below.
const PRICES_AS_OF='2026-11-25';
const MODELS=[
  {name:'Claude Opus 5.5',id:'claude-opus-5-5',inUsd:4,outUsd:20,note:'the adapter default'},
  {name:'Claude Sonnet 5.5',id:'claude-sonnet-5-5',inUsd:2,outUsd:10,note:''},
  {name:'Claude Haiku 5.5',id:'claude-haiku-5-5',inUsd:0.10,outUsd:0.50,note:''},
  {name:'Local open model (Ollama)',id:'qwen3.5:9b',inUsd:0,outUsd:0,note:'no token cost; hardware and power instead'}
];
const ENTRIES_PER_CV=3;          // YoCV takes one to three pieces of work; one model call each.
const VISIBLE_OUT_TOKENS=150;    // two bullets and their skills as JSON, measured from the sample answer shape.
const THINKING_TOKENS={low:0,high:1000}; // effort low: assumed range, to measure on a real run.
const MAX_TOKENS=4096;           // the adapter's cap, the worst case for one call.
const SCALES=[1000,10000,100000];
const tok=chars=>Math.ceil(chars/4);
const usd=v=>v===0?'$0':v<0.01?'$'+v.toFixed(4):'$'+v.toFixed(2);
const big=v=>v===0?'$0':'$'+Math.round(v).toLocaleString('en-US');

function costDoc(){
  const cv=PROMPTS[0],chars=cv.messages.reduce((n,m)=>n+m.content.length,0)+JSON.stringify(cv.schema).length;
  const inTok=tok(chars),outLow=VISIBLE_OUT_TOKENS+THINKING_TOKENS.low,outHigh=VISIBLE_OUT_TOKENS+THINKING_TOKENS.high;
  const perCv=(m,out)=>ENTRIES_PER_CV*(inTok*m.inUsd+out*m.outUsd)/1e6;
  const rows=MODELS.map(m=>'| '+m.name+' (`'+m.id+'`)'+(m.note?', '+m.note:'')+' | '+usd(perCv(m,outLow))+' to '+usd(perCv(m,outHigh))+' | '+usd(perCv(m,MAX_TOKENS))+' | '+SCALES.map(n=>big(n*perCv(m,outHigh))).join(' | ')+' |');
  return ['# Cost estimate: YoCV CV drafting','',
    'Generated by `node scripts/export-handover.js` from the real prompt. Change the assumptions in that script, not here.','',
    '## What one run is','',
    '- One CV is one to three pieces of work. Each piece is one model call (`server/cv/draft.js`), so this estimate takes '+ENTRIES_PER_CV+' calls per CV.',
    '- The QR employer check, the skill levels, the checks on every line, the Word file and the template mode make no model call. They cost nothing per run.',
    '- Retries: the adapter retries once on a rate limit or a server error. A retried call costs twice; this estimate leaves retries out.','',
    '## Tokens per call','',
    '| Part | Estimate |','| --- | --- |',
    '| Input: system prompt, one entry, skill list, output schema | about '+inTok.toLocaleString('en-US')+' tokens ('+chars.toLocaleString('en-US')+' characters at 4 a token) |',
    '| Output you see: two lines and their skills as JSON | about '+VISIBLE_OUT_TOKENS+' tokens |',
    '| Thinking, effort `low` | assumed '+THINKING_TOKENS.low+' to '+THINKING_TOKENS.high.toLocaleString('en-US')+' tokens, billed as output |',
    '| Worst case for one call | '+MAX_TOKENS.toLocaleString('en-US')+' output tokens, the adapter cap |','',
    '## Cost per CV and per month','',
    'List prices per million tokens as of '+PRICES_AS_OF+': Opus 5.5 $4 in and $20 out, Sonnet 5.5 $2 and $10, Haiku 5.5 $0.10 and $0.50. The monthly columns use the top of the range, not the worst case.','',
    '| Model | Per CV | Per CV, worst case | '+SCALES.map(n=>n.toLocaleString('en-US')+' CVs a month').join(' | ')+' |',
    '| --- | --- | --- | '+SCALES.map(()=>'---').join(' | ')+' |',
    ...rows,'',
    '## Assumptions to confirm','',
    '- GenU\'s scale. The three monthly columns are placeholders until GenU gives the number of young people who would make a CV each month.',
    '- Token counts. Run `count_tokens` (Anthropic) or read `usage` from one real call to replace the 4-characters-a-token estimate.',
    '- Thinking tokens. Opus 5.5 always thinks; the adapter asks for effort `low`. The range above is an assumption until a real run is logged.',
    '- Azure OpenAI and other OpenAI-compatible models: the same token counts apply; use that provider\'s price list.',
    '- The team\'s shared cost method. If the team agrees on a different scale or runs-per-user figure, change `SCALES` and `ENTRIES_PER_CV` in the script.',''].join('\n');
}

function files(){return Object.fromEntries([...PROMPTS.map(p=>[path.join(OUT,p.file),render(p)]),[path.join(ROOT,'handover','cost-estimate.md'),costDoc()]]);}

if(require.main===module){
  const check=process.argv.includes('--check'),stale=[];
  for(const [file,text] of Object.entries(files())){
    if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text)stale.push(path.relative(ROOT,file));}
    else{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text);console.log('wrote '+path.relative(ROOT,file));}
  }
  if(check&&stale.length){console.error('Out of date, run node scripts/export-handover.js: '+stale.join(', '));process.exit(1);}
}
module.exports={files,PROMPTS};
